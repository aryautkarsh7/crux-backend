/**
 * The specialty catalogue: the 55 from the product brief plus General Surgeon (surgeries need
 * an owner). Each entry drives listing pages, SEO copy, triage keywords and the doctor roster.
 */

export type FocusArea = { slug: string; name: string; description: string; icon: string };
export type SpecialtySeed = {
  slug: string;
  name: string;
  plural: string;
  icon: string;
  category: string;
  description: string;
  /** Clinic fee range and video fee range, used by the roster and "from ₹" chips. */
  feeRange: [number, number];
  videoRange: [number, number];
  titles: string[];
  degrees: string[];
  /** Facility categories these doctors practise from (see facility types). */
  facilityTypes: string[];
  femaleShare: number;
  /** Offers video consults at all (a veterinarian or radiologist mostly does not). */
  video: boolean;
  /** Registration body when it isn't the state medical council. */
  registrationBody?: string;
  conditions: string[];
  subSpecialties: FocusArea[];
  /** Regex alternation used by symptom triage and search. */
  keywords: string;
  whenToSee: string[];
  related: string[];
  popular?: boolean;
};

